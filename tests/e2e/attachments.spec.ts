import { test, expect } from "./fixtures";
import { createRoom } from "./api";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";

async function connect(base: string) {
  const client = new Client({ name: "botchat-test", version: "1.0.0" });
  await client.connect(new StreamableHTTPClientTransport(new URL(`${base}/mcp`)));
  return client;
}

const textOf = (r: any) => r.content.map((c: any) => c.text).join("\n");

test("shows a file attached to a message", async ({ page, server }) => {
  const room = await createRoom(server.url, "files");
  await page.goto(`${server.url}/rooms/${room.id}?as=tom`);
  await page.getByLabel("Attach a file").setInputFiles({
    name: "notes.txt",
    mimeType: "text/plain",
    buffer: Buffer.from("the quick brown fox"),
  });
  await page.getByLabel("Message").fill("here are my notes");
  await page.getByRole("button", { name: "Send" }).click();
  await expect(page.getByTestId("transcript")).toContainText("notes.txt");
});

test("serves the attached bytes back unchanged", async ({ page, server }) => {
  const room = await createRoom(server.url, "bytes");
  await page.goto(`${server.url}/rooms/${room.id}?as=tom`);
  await page.getByLabel("Attach a file").setInputFiles({
    name: "notes.txt",
    mimeType: "text/plain",
    buffer: Buffer.from("the quick brown fox"),
  });
  await page.getByLabel("Message").fill("read this");
  await page.getByRole("button", { name: "Send" }).click();
  const href = await page
    .getByTestId("transcript")
    .getByRole("link", { name: "notes.txt" })
    .getAttribute("href");
  const res = await page.request.get(new URL(href!, server.url).toString());
  expect(await res.text()).toBe("the quick brown fox");
});

